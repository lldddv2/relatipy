"""Validate the default forward model (relatipy exact Kerr) against the real data.

1. Frame/sign conventions: relatipy vs a hand-written Gillessen+09 Kepler orbit.
2. S2 CSV (NACO/SHARP + GRAVITY, 1992-2019.74) with GRAVITY 2024 Table B.1 elements.
3. S301 digitized points with Extended Data Table 2 solutions A and B.
Writes validation.md and prints it.  Run:  /usr/bin/python3 validate.py
"""
from __future__ import annotations

import numpy as np

import schedules as sch
from forward import DEG, KerrForward, load_stars, period_yr, true_anomaly

OUT = sch.HERE / "validation.md"


def kepler_sky(el, t, M6, R0):
    """Gillessen+09 Thiele-Innes: x = Dec (N), y = RA (E), z = away.  Returns ra, dec [mas], z [mas], vz [km/s]."""
    a, e = el["a_mas"], el["e"]
    i, O, w = el["i_deg"] * DEG, el["Omega_deg"] * DEG, el["omega_deg"] * DEG
    out = []
    for tt in np.atleast_1d(t):
        f = true_anomaly(tt, el, M6, R0)
        r = a * (1 - e * e) / (1 + e * np.cos(f))
        u = w + f
        X = r * (np.cos(u) * np.cos(O) - np.sin(u) * np.sin(O) * np.cos(i))
        Y = r * (np.cos(u) * np.sin(O) + np.sin(u) * np.cos(O) * np.cos(i))
        Z = r * np.sin(u) * np.sin(i)
        out.append((Y, X, Z))
    ra, de, z = np.array(out).T
    return ra, de, z


def wrms(r):
    return float(np.sqrt(np.mean(r ** 2)))


def lines_table(header, rows):
    s = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    s += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return s


def main():
    S = load_stars()
    g = S["global"]
    bh = dict(M_1e6Msun=g["M_1e6Msun"], R0_kpc=g["R0_kpc"], chi=0.0)
    alt = g["alternative"]
    bh_paper = dict(M_1e6Msun=alt["M_1e6Msun"], R0_kpc=alt["R0_kpc"], chi=0.0)
    fm = KerrForward()
    fm_tp = KerrForward(use_element_epoch=False)
    L = ["# Validation of the default forward model", "",
         "Generated by `validate.py` (relatipy KerrMcmcModel.get_ra_dec_vr, chi = 0 unless stated, "
         "dop853 rtol 1e-11). Residual = data - model. RMS per coordinate in mas.", ""]

    # ---------------------------------------------------------------- 1. conventions
    L += ["## 1. Angle and sign conventions", ""]
    el = S["stars"]["S29"]
    t = el["element_epoch"] + np.linspace(-3, 3, 13)        # S29 near apocentre: ~Newtonian
    ra, de, v = fm(el, t, t, bh)
    kra, kde, kz = kepler_sky(el, t, bh["M_1e6Msun"], bh["R0_kpc"])
    # Kepler vz from finite differences of z [mas] -> km/s
    h = 1e-3
    zp = kepler_sky(el, t + h, bh["M_1e6Msun"], bh["R0_kpc"])[2]
    zm = kepler_sky(el, t - h, bh["M_1e6Msun"], bh["R0_kpc"])[2]
    au_yr_kms = 4.740470463533348
    kvz = (zp - zm) / (2 * h) * bh["R0_kpc"] * au_yr_kms     # mas/yr * kpc = au/yr
    dmax = max(np.max(np.abs(ra - kra)), np.max(np.abs(de - kde))) * 1e3
    # remove the constant gravitational redshift + transverse Doppler offset before comparing
    dv = v - kvz
    L += [f"- S29 within +-3 yr of its 1977 osculation epoch (near apocentre, r ~ 1.5e5 r_g): relatipy vs a "
          f"hand-written Kepler orbit in the Gillessen+09 convention (x = Dec north, y = RA east, z = away, "
          f"Omega from north through east, ascending node = receding): max |d(RA, Dec)| = {dmax:.2f} uas "
          f"(Romer delay + 1PN); v_los - dz/dt = {dv.min():.2f} .. {dv.max():.2f} km/s "
          f"(gravitational redshift + transverse Doppler ~ (3/2) GM/(rc) ~ +3 km/s). "
          "Same signs and frame: relatipy alpha = +RA (east), delta = +Dec (north), v > 0 receding.",
          ]
    e2 = S["stars"]["S2"]
    tt = np.array([2018.30, 2018.3789, 2018.45])
    _, _, v2 = fm(e2, tt[:0], tt, bh)
    L += [f"- S2 line-of-sight velocity at 2018.30 / 2018.38 / 2018.45: {v2[0]:+.0f} / {v2[1]:+.0f} / {v2[2]:+.0f} km/s "
          "(receding at pericentre, then the steep drop, as the published S2 RV curve).",
          "- Published elements (both GRAVITY 2024 Table B.1 and arXiv:2607.12664, which states 'angle conventions "
          "follow Gillessen+09') can be passed to relatipy unchanged: no 180 deg shift is needed. "
          "(Foschi+ arXiv:2607.26713 Eq. 42 uses Omega_obs = Omega_GRAV + pi, omega_obs = omega_GRAV + pi, "
          "i.e. a z-flipped frame; do not mix those.)",
          "- Spin vectors are given to relatipy in the same observer axes (Dec, RA, away); the orbital pole is "
          "L = (sin O sin i, -cos O sin i, cos i).", ""]

    # ---------------------------------------------------------------- 2. S2
    d = sch.load_s2_csv(drop_duplicates=True)
    L += ["## 2. S2 astrometry CSV (GRAVITY 2020 Fig. 1), GRAVITY 2024 elements", "",
          f"{d['t'].size} rows after dropping 2 exact duplicate GRAVITY rows (2017.23968, 2017.502238). "
          "chi2/N uses the CSV errors. 'frame fit' = weighted least-squares offset + drift "
          "(x0, y0, vx0, vy0 at 2000.0) fitted to the NACO/SHARP residuals only.", ""]
    rows = []
    res_store = {}
    for lab, model, b in (("osc. epoch 2010.35", fm, bh), ("initial state at t_p", fm_tp, bh)):
        ra, de, _ = model(e2, d["t"], [], b)
        rr, rd = d["ra"] - ra, d["dec"] - de
        res_store[lab] = (rr, rd)
        for ins in ("NACO/SHARP", "GRAVITY"):
            k = d["instrument"] == ins
            c2 = np.mean(np.r_[(rr[k] / d["sigma_ra"][k]) ** 2, (rd[k] / d["sigma_dec"][k]) ** 2])
            rows.append([lab, ins, int(k.sum()), f"{wrms(rr[k]):.3f}", f"{wrms(rd[k]):.3f}",
                         f"{np.mean(rr[k]):+.3f}", f"{np.mean(rd[k]):+.3f}", f"{c2:.2f}"])
    # NACO frame fit on the osculation-epoch model
    rr, rd = res_store["osc. epoch 2010.35"]
    k = d["instrument"] == "NACO/SHARP"
    fr = {}
    for comp, r, s in (("ra", rr, d["sigma_ra"]), ("dec", rd, d["sigma_dec"])):
        A = np.c_[np.ones(k.sum()), d["t"][k] - 2000.0] / s[k][:, None]
        p, *_ = np.linalg.lstsq(A, r[k] / s[k], rcond=None)
        fr[comp] = p
        r_corr = r[k] - (p[0] + p[1] * (d["t"][k] - 2000.0))
        fr[comp + "_res"] = r_corr
    c2 = np.mean(np.r_[(fr["ra_res"] / d["sigma_ra"][k]) ** 2, (fr["dec_res"] / d["sigma_dec"][k]) ** 2])
    rows.append(["osc. epoch 2010.35 + frame fit", "NACO/SHARP", int(k.sum()), f"{wrms(fr['ra_res']):.3f}",
                 f"{wrms(fr['dec_res']):.3f}", "0", "0", f"{c2:.2f}"])
    kk = k & (d["t"] >= 2002.5)
    L += lines_table(["model", "instrument", "N", "RMS RA", "RMS Dec", "mean RA", "mean Dec", "chi2/N"], rows)
    gtab = g["frame_offsets_naco_gravity2024"]
    rr_post = rr[kk]; rd_post = rd[kk]
    L += ["",
          f"- NACO frame fit: RA offset {fr['ra'][0]:+.3f} mas, drift {fr['ra'][1]:+.4f} mas/yr; Dec offset "
          f"{fr['dec'][0]:+.3f} mas, drift {fr['dec'][1]:+.4f} mas/yr (at 2000). GRAVITY 2024 Table B.1 frame: "
          f"x0 = {gtab['x0_mas']:+.3f}, y0 = {gtab['y0_mas']:+.3f} mas, vx0 = {gtab['vx0_mas_yr']:+.4f}, "
          f"vy0 = {gtab['vy0_mas_yr']:+.4f} mas/yr; that fit used other data (to 2022.7) and the 1PN x f_SP model, so "
          "only order-of-magnitude agreement is expected (0.1-1 mas, 0.01-0.1 mas/yr).",
          f"- NACO/SHARP from 2002.5 only (N = {int(kk.sum())}, sub-mas errors): RMS RA {wrms(rr_post):.3f}, "
          f"Dec {wrms(rd_post):.3f} mas before the frame fit. The 1992-2002 SHARP/NACO points have 2-5 mas errors.",
          "- GRAVITY residual RMS ~0.1 mas against typical errors 0.05-0.2 mas: the 2024 elements (fitted with "
          "1PN x f_SP = 1.135 and different data) reproduce the 2016-2019 GRAVITY points with exact Kerr at chi = 0 "
          "to a level well below the S301 (207 uas) and comparable to the friends' (30-50 uas) future errors.",
          "- Using the elements as an initial state at t_p instead of at their 2010.35 osculation epoch worsens "
          "NACO by ~1-4 mas and GRAVITY by ~2x: the element epoch must be respected (default).", ""]
    # GRAVITY residuals by year
    kg = d["instrument"] == "GRAVITY"
    yrs = np.floor(d["t"][kg]).astype(int)
    rows = []
    for y in sorted(set(yrs)):
        m = yrs == y
        rows.append([y, int(m.sum()), f"{np.mean(rr[kg][m]):+.3f}", f"{np.mean(rd[kg][m]):+.3f}",
                     f"{wrms(rr[kg][m]):.3f}", f"{wrms(rd[kg][m]):.3f}"])
    L += ["GRAVITY residuals per year (osc. epoch model):", ""]
    L += lines_table(["year", "N", "mean RA", "mean Dec", "RMS RA", "RMS Dec"], rows)
    L += [""]

    # ---------------------------------------------------------------- 3. S301
    s = sch.load_s301_digitized()
    m = s["flag"] == "matched"
    L += ["## 3. S301 digitized positions (Nature 2026 figure), Extended Data Table 2", "",
          "19 points matched to Extended Data Table 1 epochs (|dt| < 0.004 yr; digitized years differ from the "
          f"table by up to {np.max(np.abs(s['t'][m] - s['t_digitized'][m])) * 365.25:.1f} d), model evaluated at the "
          "table epochs. The 2023.577 point has no table epoch and is excluded from the RMS and listed separately. "
          "chi2 uses 207 uas per coordinate; chi2_fig uses the digitized error-bar half-widths.", ""]
    rows = []
    unm = []
    for sol in ("S301A", "S301B"):
        el = S["stars"][sol]
        variants = [("paper M, R0; osc. epoch t_p - P/2 (default)", bh_paper, el["element_epoch"]),
                    ("GRAVITY 2024 M, R0; osc. epoch t_p - P/2", bh, el["element_epoch"]),
                    ("paper M, R0; osc. epoch 2017.0", bh_paper, 2017.0),
                    ("paper M, R0; osc. epoch 2022.9", bh_paper, 2022.9),
                    ("paper M, R0; osc. epoch t_p (initial state at pericentre)", bh_paper, el["t_p"]),
                    ("paper M, R0; osc. epoch 2023.3 (after pericentre)", bh_paper, 2023.3),
                    ("paper M, R0; osc. epoch 2027.47 (next apocentre)", bh_paper, el["t_p"] + 4.341)]
        for lab, b, te in variants:
            ra, de, _ = fm(dict(el, element_epoch=te), s["t"], [], b)
            rr, rd = s["ra"] - ra, s["dec"] - de
            c2 = np.sum((rr[m] / 0.207) ** 2 + (rd[m] / 0.207) ** 2)
            c2f = np.sum((rr[m] / s["halfwidth_ra"][m]) ** 2 + (rd[m] / s["halfwidth_dec"][m]) ** 2)
            rows.append([sol, lab, f"{wrms(rr[m]):.3f}", f"{wrms(rd[m]):.3f}", f"{np.mean(rr[m]):+.3f}",
                         f"{np.mean(rd[m]):+.3f}", f"{c2:.1f}", f"{c2f:.0f}"])
            if lab.endswith("(default)"):
                unm.append((sol, rr[~m][0], rd[~m][0]))
                if sol == "S301A":
                    per_point = [[f"{s['t'][j]:.4f}", f"{rr[j]:+.3f}", f"{rd[j]:+.3f}",
                                  f"{s['halfwidth_ra'][j]:.2f}", f"{s['halfwidth_dec'][j]:.2f}", s["flag"][j]]
                                 for j in range(s["t"].size)]
    L += lines_table(["solution", "M, R0 / epoch", "RMS RA", "RMS Dec", "mean RA", "mean Dec",
                      "chi2 (38 dof-ish)", "chi2_fig"], rows)
    elA, elB = S["stars"]["S301A"], S["stars"]["S301B"]
    tt = np.linspace(2017, 2041, 3000)
    ra_a, de_a, v_a = fm(elA, tt, tt, bh_paper)
    ra_b, de_b, v_b = fm(elB, tt, tt, bh_paper)
    k23 = np.abs(tt - 2023.126) > 0.3
    L += ["", "Per-point residuals, S301A default model (mas):", ""]
    L += lines_table(["t", "dRA", "dDec", "halfwidth RA", "halfwidth Dec", "flag"], per_point)
    L += ["",
          "- Unmatched 2023.577 point: residual " + "; ".join(f"{a} ({x:+.2f}, {y:+.2f}) mas" for a, x, y in unm) +
          ". Kept in the data file, flagged, excluded by default (ScheduleConfig.s301_include_unmatched).",
          f"- A vs B sky tracks (chi = 0, paper M/R0), 2017-2041: max separation {np.max(np.hypot(ra_a - ra_b, de_a - de_b)):.2f} mas; "
          f"away from the 2023 pericentre (|t - t_p| > 0.3 yr) median {np.median(np.hypot(ra_a - ra_b, de_a - de_b)[k23]) * 1e3:.0f} uas. "
          f"v_los: A {v_a[np.argmin(np.abs(tt - 2031.81))]:+.0f} vs B {v_b[np.argmin(np.abs(tt - 2031.81))]:+.0f} km/s at 2031.81; "
          f"max |v_A + v_B| = {np.max(np.abs(v_a + v_b)):.0f} km/s vs max |v| = {np.max(np.abs(v_a)):.0f} km/s "
          "(z-mirror: RV flips sign; the difference is the different e, i and the even redshift terms).",
          "- Osculation epoch: the published elements reproduce the figure only if they are osculating BEFORE the "
          "2023.13 pericentre (any epoch 2017-2022.9: chi2 within ~3 of each other). Osculating after pericentre "
          "gives RMS ~3 mas: across pericentre the osculating omega jumps by the Schwarzschild advance (~2 deg), "
          "i.e. ~3 mas at 83 mas. Default: preceding apocentre t_p - P/2 = 2018.785, as GRAVITY 2024 for S2/S29.",
          "- An initial state AT pericentre (e = 0.983) would be the worst choice in general: there the Kepler "
          "(a, e) <-> state map is ill-conditioned at 1PN (E ~ (1 - e) GM/r_p while v^2/c^2 ~ 0.7%).",
          "- With the default epoch the RMS is 0.23 mas in RA and 0.47 mas in Dec (chi2 ~120 for 38 numbers at "
          "207 uas, against the published 25.9 / 25.5). The excess is mostly in Dec and in single points "
          "(2023.26, 2023.43, 2023.51, 2024.33, 2024.41, 2025.52 at 0.5-1 mas), which points to digitization error "
          "or figure-level differences, not to the elements. The digitized error-bar half-widths (0.02-1.6 mas) are "
          "not the 207 uas of the paper (e.g. 0.02 mas in RA at 2024.2325 is a digitization artefact); the "
          "schedules use 207 uas. Good enough to confirm elements, epochs and conventions, not for a refit; "
          "manual review of the digitized file is still pending.",
          "- The unmatched 2023.577 point lies on the orbit (residual ~0.55 mas in Dec, like its neighbours), so "
          "it is probably a real plotted point without an Extended Data Table 1 entry (or a duplicated/misread "
          "symbol); it stays excluded by default.", ""]
    txt = "\n".join(L)
    OUT.write_text(txt + "\n")
    print(txt)


if __name__ == "__main__":
    main()
