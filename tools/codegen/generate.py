"""Regenerate the committed C sources produced by ``relatipy._codegen``.

Each specification ``tools/codegen/specs/<name>.py`` defines ``build()``,
which returns ``{repository-relative path: text}``.  This script prepends a
header naming the specification and writes the files, or with ``--check``
reports which committed files differ.

Usage, from the repository root::

    python tools/codegen/generate.py              # regenerate every spec
    python tools/codegen/generate.py ring_field   # one spec
    python tools/codegen/generate.py --check      # exit 1 if any file differs

SymPy is required (``pip install relatipy[symbolic]``).
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path
from types import ModuleType

ROOT = Path(__file__).resolve().parents[2]
SPECS = Path(__file__).resolve().parent / "specs"


def _ensure_source_path() -> None:
    source = str(ROOT / "src")
    if source not in sys.path:
        sys.path.insert(0, source)


def spec_names() -> list[str]:
    """Names of every specification, sorted."""
    return sorted(path.stem for path in SPECS.glob("*.py") if not path.stem.startswith("_"))


def load_spec(name: str) -> ModuleType:
    """Import ``specs/<name>.py`` as a module."""
    _ensure_source_path()
    path = SPECS / f"{name}.py"
    if not path.is_file():
        raise SystemExit(f"unknown specification {name!r}; available: {', '.join(spec_names())}")
    spec = importlib.util.spec_from_file_location(f"relatipy_codegen_spec_{name}", path)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def header(name: str) -> str:
    """Comment block that opens every generated file."""
    import sympy

    return (
        "/*\n"
        f" * Generated by tools/codegen/generate.py from tools/codegen/specs/{name}.py.\n"
        " * Do not edit: change the specification and regenerate with\n"
        f" *     python tools/codegen/generate.py {name}\n"
        f" * SymPy {sympy.__version__}.\n"
        " */\n"
    )


def render(name: str) -> dict[Path, str]:
    """Generated files of one specification, keyed by absolute path."""
    module = load_spec(name)
    files = module.build()
    prefix = header(name)
    return {ROOT / path: prefix + text for path, text in files.items()}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("specs", nargs="*", help="specification names (default: all)")
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    arguments = parser.parse_args(argv)
    names = arguments.specs or spec_names()
    stale = []
    for name in names:
        for path, text in render(name).items():
            relative = path.relative_to(ROOT)
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current == text:
                print(f"up to date  {relative}")
                continue
            if arguments.check:
                stale.append(relative)
                print(f"differs     {relative}")
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote       {relative}")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
