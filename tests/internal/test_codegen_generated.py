# -- ring field --------------------------------------------------------------
def _ring_reference(d, z, radius, softening, mass):
    z2 = z * z + softening * softening
    p = np.sqrt((d + radius) ** 2 + z2)
    q2 = (d - radius) ** 2 + z2
    m = 4.0 * radius * d / p**2
    k, e = ellipk(m), ellipe(m)
    a_d = -(mass / (np.pi * p * d)) * (k + e * (d * d - radius * radius - z2) / q2)
    a_z = -(2.0 * mass / (np.pi * p * q2)) * e * z
    potential = -2.0 * mass * k / (np.pi * p)
    return m, k, e, np.array([a_d, a_z, potential])


def _ring(native, d, z, radius, softening, mass):
    m = native.rp_force_generated_ring_parameter(d, z, radius, softening)
    field = np.zeros(3)
    native.rp_force_generated_ring_field(d, z, radius, softening, mass, ellipk(m), ellipe(m),
                                         _pointer(field))
    return m, field


def test_ring_field_matches_numpy(native) -> None:
    generator = np.random.default_rng(11)
    for _ in range(200):
        d = generator.uniform(0.01, 30.0)
        z = generator.uniform(-10.0, 10.0)
        radius = generator.uniform(0.1, 20.0)
        softening = generator.uniform(1e-3, 0.5)
        mass = generator.uniform(1e-4, 1.0)
        m_ref, k, e, expected = _ring_reference(d, z, radius, softening, mass)
        m, field = _ring(native, d, z, radius, softening, mass)
        assert m == pytest.approx(m_ref, rel=1e-14)
        # a_d is a difference of K and an E term; bound its error by their size.
        z2 = z * z + softening * softening
        p = np.sqrt((d + radius) ** 2 + z2)
        q2 = (d - radius) ** 2 + z2
        terms = mass / (np.pi * p * d) * (k + e * abs(d * d - radius * radius - z2) / q2)
        assert abs(field[0] - expected[0]) <= 1e-13 * terms
        np.testing.assert_allclose(field[1:], expected[1:], rtol=1e-13, atol=0)


def test_ring_field_is_the_gradient_of_its_potential(native) -> None:
    radius, softening, mass, step = 3.0, 0.05, 0.2, 1e-5
    for d, z in ((1.0, 0.4), (5.0, -2.0), (2.9, 0.01), (0.2, 3.0)):
        _, field = _ring(native, d, z, radius, softening, mass)
        potential = lambda dd, zz: _ring(native, dd, zz, radius, softening, mass)[1][2]  # noqa: E731
        a_d = -(potential(d + step, z) - potential(d - step, z)) / (2 * step)
        a_z = -(potential(d, z + step) - potential(d, z - step)) / (2 * step)
        np.testing.assert_allclose(field[:2], [a_d, a_z], rtol=1e-6, atol=1e-9)


# -- projection -------------------------------------------------------------
def _metric(mass, spin, r, theta):
    sine2, cosine2 = np.sin(theta) ** 2, np.cos(theta) ** 2
    sigma = r * r + spin * spin * cosine2
    delta = r * r - 2.0 * mass * r + spin * spin
    common = 2.0 * mass * r / sigma
    g = np.zeros((4, 4))
    g[0, 0] = -(1.0 - common)
    g[0, 3] = g[3, 0] = -spin * sine2 * common
    g[1, 1] = sigma / delta
    g[2, 2] = sigma
    g[3, 3] = sine2 * (r * r + spin * spin + spin * spin * sine2 * common)
    return g


def _projection_reference(mass, spin, x, u, acceleration):
    _, r, theta, phi = x
    rho = np.hypot(r, spin)
    st, ct, sp_, cp = np.sin(theta), np.cos(theta), np.sin(phi), np.cos(phi)
    jacobian = np.array([
        [r / rho * st * cp, rho * ct * cp, -rho * st * sp_],
        [r / rho * st * sp_, rho * ct * sp_, rho * st * cp],
        [ct, -r * st, 0.0],
    ])
    covector = np.concatenate([[0.0], acceleration @ jacobian])
    inverse = np.linalg.inv(_metric(mass, spin, r, theta))
    return inverse @ covector + u * (u @ covector), covector


def _timelike(mass, spin, x, spatial):
    g = _metric(mass, spin, x[1], x[2])
    a = g[0, 0]
    b = 2.0 * g[0, 3] * spatial[2]
    c = g[1, 1] * spatial[0] ** 2 + g[2, 2] * spatial[1] ** 2 + g[3, 3] * spatial[2] ** 2 + 1.0
    roots = np.roots([a, b, c])
    return np.array([np.max(roots.real), *spatial])


def test_projection_matches_numpy_and_is_orthogonal(native) -> None:
    generator = np.random.default_rng(12)
    for spin in (-0.9, 0.0, 0.5, 0.99):
        for _ in range(40):
            r = generator.uniform(2.5, 80.0)
            x = np.array([0.0, r, generator.uniform(0.1, np.pi - 0.1), generator.uniform(-3, 3)])
            spatial = generator.normal(scale=0.2, size=3) / np.array([1.0, r, r])
            u = _timelike(1.0, spin, x, spatial)
            acceleration = generator.normal(scale=1e-3, size=3)
            force = np.zeros(4)
            status = native.rp_test_projection(1.0, spin, _pointer(x), _pointer(u),
                                               _pointer(acceleration), _pointer(force))
            assert status == 0
            expected, covector = _projection_reference(1.0, spin, x, u, acceleration)
            np.testing.assert_allclose(force, expected, rtol=1e-11, atol=1e-13 * np.max(np.abs(expected)))
            g = _metric(1.0, spin, x[1], x[2])
            scale = np.abs(g @ u) @ np.abs(force)
            assert abs((g @ u) @ force) <= 1e-13 * scale


# -- corrected Kerr RHS -----------------------------------------------------
def _grid():
    generator = np.random.default_rng(13)
    for spin in (-0.99, -0.5, 0.0, 0.5, 0.9, 0.99):
        horizon = 1.0 + np.sqrt(1.0 - spin * spin)
        for r in (horizon * (1 + 1e-3), horizon * 1.01, horizon + 0.1, 3.0, 6.0, 1e2, 1e4, 1e6):
            for theta in (1e-6, 1e-3, 0.1, 1.0, np.pi / 2, np.pi / 2 + 1e-9, np.pi - 1e-4,
                          np.pi - 1e-6):
                for _ in range(4):
                    x = np.array([0.0, r, theta, 0.3])
                    u = np.array([1.0 + generator.random(), generator.normal(scale=0.3),
                                  generator.normal(scale=0.3) / r, generator.normal(scale=0.3) / r])
                    yield spin, x, u


@pytest.fixture(scope="module")
def reference_rhs():
    sp = pytest.importorskip("sympy")
    mpmath = pytest.importorskip("mpmath")
    from relatipy._codegen.kerr import geodesic_acceleration, kerr_symbols

    s = kerr_symbols()
    function = sp.lambdify((s.mass, s.spin, s.r, s.theta, *s.u),
                           geodesic_acceleration(s, prepared=False), modules="mpmath")

    def evaluate(spin, x, u):
        with mpmath.workdps(40):
            values = function(mpmath.mpf(1), mpmath.mpf(spin), mpmath.mpf(x[1]), mpmath.mpf(x[2]),
                              *(mpmath.mpf(float(item)) for item in u))
            return np.array([float(value) for value in values])

    return evaluate


def test_generated_kerr_rhs_matches_the_corrected_kernel(native, reference_rhs) -> None:
    """Agreement to 1e-12 relative, component by component.

    Both kernels read the same prepared state, so they share its rounding.
    Where they differ by more than 1e-12 in a component (an ill-conditioned
    small component), the generated value must be no farther than the
    corrected one, plus 1e-12 relative, from a 40-digit evaluation of the
    exact contraction at the same binary inputs.
    """
    checked = disagreements = 0
    for spin, x, u in _grid():
        corrected, generated = np.zeros(4), np.zeros(4)
        assert native.rp_test_rhs(0, spin, _pointer(x), _pointer(u), _pointer(corrected)) == 0
        assert native.rp_test_rhs(1, spin, _pointer(x), _pointer(u), _pointer(generated)) == 0
        checked += 1
        assert np.max(np.abs(generated - corrected)) <= 1e-12 * np.max(np.abs(corrected))
        relative = np.abs(generated - corrected) / np.abs(corrected)
        if np.all(relative <= 1e-12):
            continue
        disagreements += 1
        exact = reference_rhs(spin, x, u)
        assert np.all(
            np.abs(generated - exact) <= np.abs(corrected - exact) + 1e-12 * np.abs(exact)
        )
    assert checked == 6 * 8 * 8 * 4
    assert disagreements <= checked // 50
